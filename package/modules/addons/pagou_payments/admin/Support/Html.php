    public static function e(mixed $value): string
    {
        return htmlspecialchars((string) $value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }

    /** Trusted, bundled brand asset rendered inline, never supplied by a request. */
    public static function logo(string $class): string
    {
        $svg = (string) file_get_contents(dirname(__DIR__, 2) . '/assets/logo.svg');
        return str_replace('<svg ', '<svg class="' . self::e($class) . '" role="img" aria-label="Pagou" focusable="false" ', $svg);
    }

    /** @param array<string, scalar|null> $attributes */
    public static function attributes(array $attributes): string
    {
        $rendered = [];
        foreach ($attributes as $name => $value) {
            if ($value === null || $value === false) {
                continue;
            }
            $rendered[] = self::e($name) . ($value === true ? '' : '="' . self::e($value) . '"');
        }

        return $rendered === [] ? '' : ' ' . implode(' ', $rendered);
    }

    public static function badge(string $label, string $tone = 'neutral'): string
    {
        $allowed = ['success', 'warning', 'danger', 'info', 'neutral'];
        $tone = in_array($tone, $allowed, true) ? $tone : 'neutral';

        return '<span class="pagou-badge pagou-badge--' . self::e($tone) . '">' . self::e($label) . '</span>';
    }

